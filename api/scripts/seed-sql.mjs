/**
 * Builds SQL that replaces all content with a PortfolioDto (used for the initial seed).
 * Shared by scripts/generate-seed.mjs and the tests.
 */

/** @param {unknown} value */
function sql(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? '1' : '0';
  return `'${String(value).replaceAll("'", "''")}'`;
}

/** @param {unknown[]} values */
const list = (values) => values.map(sql).join(', ');

/** @param {import('../../src/app/core/api/api.models').PortfolioDto} portfolio */
export function buildSeedSql(portfolio) {
  const lines = [
    '-- Generated by scripts/generate-seed.mjs from src/app/core/mock/mock-data.ts. Do not edit.',
    'DELETE FROM projects;',
    'DELETE FROM skill_groups;',
    'DELETE FROM roles;',
  ];
  for (const p of portfolio.projects) {
    lines.push(
      'INSERT INTO projects (id, sort_order, name, type, year, stack, description, art_variant, coordinates, layout_class, url) ' +
        `VALUES (${list([p.id, p.order, p.name, p.type, p.year, p.stack, p.description, p.artVariant, JSON.stringify(p.coordinates), p.layoutClass, p.url])});`,
    );
  }
  for (const g of portfolio.skills) {
    lines.push(
      'INSERT INTO skill_groups (id, sort_order, title, items) ' +
        `VALUES (${list([g.id, g.order, g.title, JSON.stringify(g.items)])});`,
    );
  }
  for (const r of portfolio.experience.roles) {
    lines.push(
      'INSERT INTO roles (id, sort_order, year, title, subtitle, is_current) ' +
        `VALUES (${list([r.id, r.order, r.year, r.title, r.subtitle, r.isCurrent])});`,
    );
  }
  return lines.join('\n') + '\n';
}
